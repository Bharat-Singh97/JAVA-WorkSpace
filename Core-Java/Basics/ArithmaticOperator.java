public class ArithmaticOperator{
	public static void main(String a[]) {
		int num1 = 11;
		int num2 = 3;

		int add = num1 + num2; // 14
		int sub = num1 - num2;  //8
		int mul = num1 * num2; // 33
		double div = (double)num1 / (double)num2; // 3.6666666666666665
		int mod = num1 % num2; //2

		System.out.println("Sum of two numbers:" + add);
		System.out.println("Substraction of two numbers:" + sub);
		System.out.println("Product of two numbers:" + mul);
		System.out.println("Division of two numbers:" + div);
		System.out.println("Modules of two numbers:" + mod);





	}
}